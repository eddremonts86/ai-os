#!/usr/bin/env python3
"""Distribute AI-OS agents to every CLI that supports custom subagents.

  python3 setup/render-agents.py [--home DIR] [--check]

Source of truth: ai-config/agents/<name>.md (shared) and context/personal/agents/<name>.md (yours, git-ignored;
same name replaces the shared one). Each is Markdown with YAML frontmatter:

  ---
  name: docs-writer                  # required, = file name, lowercase-hyphen
  description: When to use it.       # required: every CLI delegates on this
  clis:                              # optional per-CLI extras, merged into that CLI's file as is
    claude: {model: sonnet, tools: [Read, Edit]}
    codex: {model_reasoning_effort: medium}
    opencode: {steps: 40}
  ---
  The body is the agent's system prompt.

Written per CLI, only when that CLI's home folder exists:
  Claude Code  ~/.claude/agents/<name>.md            (name, description + extras)
  Gemini CLI   ~/.gemini/agents/<name>.md            (name, description + extras)
  opencode     ~/.config/opencode/agents/<name>.md   (description, mode: subagent + extras)
  Codex        ~/.codex/agents/<name>.toml           (name, description, developer_instructions + extras)
Hermes and Antigravity have no file-based agents yet; their agents reach the same instructions as skills.

Every written file carries a marker line. Marked files whose agent no longer exists are removed; a file without the
marker is yours and is never overwritten. --check reports what would change and exits 1 if anything is stale.
"""

import argparse
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCES = [ROOT / "ai-config" / "agents", ROOT / "context" / "personal" / "agents"]
MARKER = "generated by ai-os setup/render-agents.py"
NAME_RE = re.compile(r"^[a-z0-9][a-z0-9-]*$")
# cli -> (folder under HOME that proves the CLI is installed, agents folder, file suffix)
TARGETS = {
    "claude": (".claude", ".claude/agents", ".md"),
    "gemini": (".gemini", ".gemini/agents", ".md"),
    "opencode": (".config/opencode", ".config/opencode/agents", ".md"),
    "codex": (".codex", ".codex/agents", ".toml"),
}


def parse(path):
    import yaml
    text = path.read_text(encoding="utf-8")
    m = re.match(r"^---\n(.*?)\n---\n?(.*)$", text, re.S)
    if not m:
        raise ValueError(f"{path}: needs YAML frontmatter between --- lines")
    meta = yaml.safe_load(m.group(1)) or {}
    body = m.group(2).strip() + "\n"
    name, desc = meta.get("name"), meta.get("description")
    if not isinstance(name, str) or not NAME_RE.match(name) or name != path.stem:
        raise ValueError(f"{path}: name must be lowercase-hyphen and equal the file name ({path.stem})")
    if not isinstance(desc, str) or not desc.strip():
        raise ValueError(f"{path}: description is required")
    clis = meta.get("clis") or {}
    unknown = set(clis) - set(TARGETS)
    if unknown:
        raise ValueError(f"{path}: unknown clis {sorted(unknown)}; known: {sorted(TARGETS)}")
    return {"name": name, "description": " ".join(desc.split()), "body": body, "clis": clis}


def load_agents(sources=SOURCES):
    agents = {}
    for folder in sources:
        for path in sorted(Path(folder).glob("*.md")) if Path(folder).is_dir() else []:
            if path.name.lower() == "readme.md":
                continue
            agent = parse(path)
            agents[agent["name"]] = agent  # personal (later) replaces shared
    return agents


def _yaml_front(fields):
    import yaml
    dumped = yaml.safe_dump(fields, sort_keys=False, allow_unicode=True, width=10_000).strip()
    return f"---\n# {MARKER}\n{dumped}\n---\n"


def _toml_value(v):
    if isinstance(v, bool):
        return "true" if v else "false"
    if isinstance(v, (int, float)):
        return str(v)
    if isinstance(v, str):
        return json.dumps(v, ensure_ascii=False)  # a JSON string is a valid TOML basic string
    if isinstance(v, list):
        return "[" + ", ".join(_toml_value(x) for x in v) + "]"
    raise ValueError(f"codex extras support scalars and lists only, got {type(v).__name__}")


def render(cli, agent):
    extras = agent["clis"].get(cli) or {}
    if cli == "codex":
        fields = {"name": agent["name"], "description": agent["description"], **extras,
                  "developer_instructions": agent["body"]}
        lines = [f"# {MARKER}; edit the agent's source, not this file"]
        lines += [f"{k} = {_toml_value(v)}" for k, v in fields.items()]
        return "\n".join(lines) + "\n"
    if cli == "opencode":
        fields = {"description": agent["description"], "mode": "subagent", **extras}
    else:
        fields = {"name": agent["name"], "description": agent["description"], **extras}
    return _yaml_front(fields) + "\n" + agent["body"]


def generated(path):
    """True for a file this script wrote: the marker is on its first or second line, where render() puts it."""
    head = path.read_text(encoding="utf-8").splitlines()[:2]
    return any(line.startswith(f"# {MARKER}") for line in head)


def sync(home, agents, check=False):
    """Return a list of (action, path, cli) where action is write, remove, skip-user-file or ok."""
    report = []
    for cli, (probe, folder, suffix) in TARGETS.items():
        if not (home / probe).is_dir():
            continue
        out = home / folder
        wanted = {f"{n}{suffix}": render(cli, a) for n, a in agents.items()}
        for fname, content in wanted.items():
            path = out / fname
            if path.is_symlink() or (path.exists() and not generated(path)):
                report.append(("skip-user-file", path, cli))
                continue
            if path.exists() and path.read_text(encoding="utf-8") == content:
                report.append(("ok", path, cli))
                continue
            report.append(("write", path, cli))
            if not check:
                out.mkdir(parents=True, exist_ok=True)
                path.write_text(content, encoding="utf-8")
        for path in sorted(out.glob(f"*{suffix}")) if out.is_dir() else []:
            if path.name not in wanted and not path.is_symlink() and generated(path):
                report.append(("remove", path, cli))
                if not check:
                    path.unlink()
    return report


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--home", type=Path, default=Path.home())
    ap.add_argument("--check", action="store_true", help="report only; exit 1 when something would change")
    a = ap.parse_args(argv)
    try:
        agents = load_agents()
    except (ValueError, ImportError) as e:
        print(f"render-agents: {e}", file=sys.stderr)
        return 2
    report = sync(a.home, agents, check=a.check)
    for action, path, _ in report:
        if action != "ok":
            print(f"  {action:15} {path}")
    changed = sum(1 for act, _, _ in report if act in ("write", "remove"))
    clis = sorted({cli for _, _, cli in report})
    print(f"{len(agents)} agent(s) -> {', '.join(clis) or 'no CLI found'}; {changed} change(s)")
    return 1 if a.check and changed else 0


if __name__ == "__main__":
    sys.exit(main())
